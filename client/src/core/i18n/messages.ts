const catalogs: Record<Language, Record<MessageKey, string>> = { tr, en }

export function hasMessage(key: string): key is MessageKey {
  return key in tr
}

/** `{0}`, `{1}` ... yer tutucularını sırasıyla `params` ile doldurur. */
export function translate(language: Language, key: MessageKey, params: readonly unknown[] = []): string {
  return catalogs[language][key].replace(/\{(\d+)\}/g, (match, index: string) =>
    Number(index) < params.length ? String(params[Number(index)]) : match,
  )
}
